package com.joaoeoneves.fintrack.domain.model

import java.time.LocalDate
import java.time.ZoneId
import java.time.temporal.ChronoUnit

/** Where a goal stands against its pace. */
enum class GoalStatus { ON_TRACK, BEHIND, DONE, NO_MONTHLY }

/**
 * A goal's progress: [savedCents] so far against [targetCents]. [expectedCents] is what should have been saved by
 * today (`null` without a pace to compare to); [plannedPerYearCents] is what the linked recurring items put
 * aside in a year.
 */
data class GoalProgress(
    val goal: SavingsGoal,
    val savedCents: Long,
    val expectedCents: Long?,
    val plannedPerYearCents: Long,
) {
    val targetCents: Long get() = goal.targetCents

    /** The target the bar fills against: the goal's own, else (no target) what its monthly amount sets aside a year. */
    val effectiveTargetCents: Long
        get() = if (targetCents > 0L) targetCents else plannedPerYearCents

    /** How much of the target is saved, as a 0..1 bar fill. */
    val fraction: Float
        get() =
            if (effectiveTargetCents <= 0L) {
                0f
            } else {
                (savedCents.toDouble() / effectiveTargetCents).toFloat().coerceIn(0f, 1f)
            }

    /** DONE, then NO_MONTHLY (a plan whose monthly item is gone or inactive), then BEHIND, else ON_TRACK. */
    val status: GoalStatus
        get() =
            when {
                effectiveTargetCents > 0L && savedCents >= effectiveTargetCents -> GoalStatus.DONE
                goal.recurringId != null && plannedPerYearCents <= 0L -> GoalStatus.NO_MONTHLY
                expectedCents != null && savedCents < expectedCents -> GoalStatus.BEHIND
                else -> GoalStatus.ON_TRACK
            }

    /**
     * The monthly amount that would still reach the target: the remainder over the months left (TOTAL: to the target
     * date, at least 1; ANNUAL: the rest of [today]'s year, this month included). 0 when done, `null` without a
     * target (or a TOTAL one without a date).
     */
    fun suggestedMonthlyCents(today: LocalDate): Long? {
        val remaining = effectiveTargetCents - savedCents
        val months =
            when (goal.targetType) {
                GoalTargetType.ANNUAL -> MONTHS_IN_YEAR - today.monthValue + 1L
                GoalTargetType.TOTAL ->
                    goal.targetDate?.let { maxOf(ChronoUnit.MONTHS.between(today, it), 1L) }
            }
        return when {
            effectiveTargetCents <= 0L || months == null -> null
            remaining <= 0L -> 0L
            else -> (remaining + months - 1) / months
        }
    }
}

private const val MONTHS_IN_YEAR = 12L

/**
 * Progress of [goal] as of [today]. Contributions are the union, by expense id, of the expenses generated by a
 * linked recurring item (id prefix `rec_<itemId>_`) and the expenses in the linked category; refunds subtract.
 * ANNUAL counts [today]'s calendar year, TOTAL everything from the goal's start date plus its initial amount.
 */
fun goalProgressOf(
    goal: SavingsGoal,
    expenses: List<Expense>,
    recurring: List<RecurringItem>,
    today: LocalDate,
    zone: ZoneId,
): GoalProgress {
    val prefixes = goal.countedRecurringIds.map { occurrenceIdPrefix(it) }
    val contributions =
        expenses
            .filter { expense ->
                expense.category.id == goal.linkedCategoryId || prefixes.any { expense.id.startsWith(it) }
            }.distinctBy { it.id }
            .filter { counts(goal, it.date.atZone(zone).toLocalDate(), today) }
    val initial = if (goal.targetType == GoalTargetType.TOTAL) goal.initialCents else 0L
    return GoalProgress(
        goal = goal,
        savedCents = initial + contributions.netCents(),
        expectedCents = if (goal.targetCents > 0L) expectedByToday(goal, today) else null,
        plannedPerYearCents = plannedPerYear(goal, recurring, today),
    )
}

private fun counts(
    goal: SavingsGoal,
    date: LocalDate,
    today: LocalDate,
): Boolean =
    when (goal.targetType) {
        GoalTargetType.ANNUAL -> date.year == today.year
        GoalTargetType.TOTAL -> date >= goal.startDate
    }

/**
 * What should be saved by [today]: ANNUAL pro rata by the day of the year, TOTAL linear from the start date to the
 * target date (`null` without a target date).
 */
fun expectedByToday(
    goal: SavingsGoal,
    today: LocalDate,
): Long? =
    when (goal.targetType) {
        GoalTargetType.ANNUAL -> goal.targetCents * today.dayOfYear / today.lengthOfYear()
        GoalTargetType.TOTAL -> goal.targetDate?.let { linearExpected(goal, it, today) }
    }

private fun linearExpected(
    goal: SavingsGoal,
    end: LocalDate,
    today: LocalDate,
): Long {
    val total = ChronoUnit.DAYS.between(goal.startDate, end)
    val elapsed = ChronoUnit.DAYS.between(goal.startDate, today)
    return when {
        total <= 0L -> if (today >= end) goal.targetCents else 0L
        else -> goal.targetCents * elapsed.coerceIn(0L, total) / total
    }
}

/** The yearly amount the goal's linked, active, not ended EXPENSE recurring items set aside (monthly ones x12). */
fun plannedPerYear(
    goal: SavingsGoal,
    recurring: List<RecurringItem>,
    today: LocalDate,
): Long = annualizedCents(recurring.filter { it.id in goal.countedRecurringIds }, RecurringType.EXPENSE, today)
