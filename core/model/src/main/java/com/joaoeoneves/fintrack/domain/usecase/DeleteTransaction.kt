package com.joaoeoneves.fintrack.domain.usecase

import com.joaoeoneves.fintrack.domain.model.Expense
import com.joaoeoneves.fintrack.domain.model.Income
import com.joaoeoneves.fintrack.domain.model.RecurringItem
import com.joaoeoneves.fintrack.domain.model.RecurringType
import com.joaoeoneves.fintrack.domain.model.Transaction
import com.joaoeoneves.fintrack.domain.model.parseOccurrenceId
import com.joaoeoneves.fintrack.domain.repository.ExpenseRepository
import com.joaoeoneves.fintrack.domain.repository.IncomeRepository
import com.joaoeoneves.fintrack.domain.repository.RecurringRepository
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.flow.first
import java.time.LocalDate
import javax.inject.Inject

/**
 * The occurrence of recurring item [itemId] ([itemName]) on [date] that a deletion turned into a skipped one.
 * [newlySkipped] is false when it was already skipped, so an undo must not un-skip it.
 */
data class IgnoredOccurrence(
    val itemId: String,
    val itemName: String,
    val date: LocalDate,
    val newlySkipped: Boolean,
)

/** A deleted [transaction], kept for the undo, and the occurrence its deletion skipped, if any. */
data class DeletedTransaction(
    val transaction: Transaction,
    val ignored: IgnoredOccurrence? = null,
)

/**
 * Deletes a transaction. Deleting the expense generated by a recurring item also marks that occurrence as skipped,
 * otherwise auto-post would re-create it. Write order avoids racing an auto-post pass already running: the skip
 * is written before the delete, and on undo the expense is restored before the skip is removed.
 */
class DeleteTransaction
    @Inject
    constructor(
        private val expenseRepository: ExpenseRepository,
        private val incomeRepository: IncomeRepository,
        private val recurringRepository: RecurringRepository,
    ) {
        suspend operator fun invoke(transaction: Transaction): Result<DeletedTransaction> =
            when (transaction) {
                is Income -> incomeRepository.deleteIncome(transaction.id).map { DeletedTransaction(transaction) }
                is Expense -> deleteExpense(transaction)
            }

        /** Restores [deleted] and, when its deletion skipped an occurrence, un-skips it. */
        suspend fun undo(deleted: DeletedTransaction): Result<Unit> {
            val restored =
                when (val transaction = deleted.transaction) {
                    is Expense -> expenseRepository.addExpense(transaction).map { }
                    is Income -> incomeRepository.addIncome(transaction).map { }
                }
            val ignored = deleted.ignored?.takeIf { it.newlySkipped }
            return if (restored.isFailure || ignored == null) {
                restored
            } else {
                recurringRepository.unskipOccurrences(ignored.itemId, setOf(ignored.date))
            }
        }

        private suspend fun deleteExpense(expense: Expense): Result<DeletedTransaction> {
            val ref = parseOccurrenceId(expense.id)
            val item =
                ref?.let {
                    runCatching { recurringRepository.observeRecurring().first() }
                        .onFailure { e -> if (e is CancellationException) throw e }
                        .getOrNull()
                        ?.firstOrNull { it.id == ref.itemId && it.type == RecurringType.EXPENSE }
                }
            return if (ref == null || item == null) {
                expenseRepository.deleteExpense(expense.id).map { DeletedTransaction(expense) }
            } else {
                deleteAndSkip(expense, item, ref.date)
            }
        }

        /** Skips [date] of [item] (unless already skipped) and deletes [expense]; a failed delete undoes the skip. */
        private suspend fun deleteAndSkip(
            expense: Expense,
            item: RecurringItem,
            date: LocalDate,
        ): Result<DeletedTransaction> {
            val newlySkipped = date !in item.skipped
            val skip =
                if (newlySkipped) {
                    recurringRepository.skipOccurrences(item.id, setOf(date), advanceTo = null)
                } else {
                    Result.success(Unit)
                }
            val delete = if (skip.isSuccess) expenseRepository.deleteExpense(expense.id) else skip
            if (delete.isFailure && skip.isSuccess && newlySkipped) {
                recurringRepository.unskipOccurrences(item.id, setOf(date))
            }
            return delete.map {
                DeletedTransaction(expense, IgnoredOccurrence(item.id, item.name, date, newlySkipped))
            }
        }
    }
